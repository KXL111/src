#ifndef USART_PDC_H
#define USART_PDC_H

#include "bsp.h"


/********************************** 出错代码定义 ********************************************************/
#define US_NO_ERR                      0
#define US_ERR_INVALID_PORT            1
#define US_ERR_NULL_PTR                2
#define US_ERR_READ_TIMEOUT            3
 
/********************************** 外部函数声明 *******************************************************/
/* 串口0初始化 */
void Usart0_Init ( void );

/* 串口1初始化 */
void Usart1_Init ( void );

/* 发送单字节数据
*  参数：pUSART : 串口数据结构首地址
*        ch     : 待发送字节数据
*/
void UsartPutChar(AT91PS_USART pUSART, INT8U ch);

/* 发送字符串数据
*  参数：pUSART : 串口数据结构首地址
*        psrc   : 待发字符串数据首地址，当遇到'\0'结束	
*/
unsigned int UsartSendString(AT91PS_USART pUSART,char *psrc);

/* 串口数据发送
*  参数：id     : 串口编号(0~1)
*        psrc   : 待发送数据首地址
*        size   : 发送长度
*        timeout: 发送等待的最长时间(==0时，表示无限时等待)
*/
INT8U UsartWrite(INT8U id,INT8U *psrc,INT32U size,INT16U timeout); 

/* 串口数据读取
*  参数：id     : 串口编号(0~1)
*        pdest  : 接受缓冲区首地址
*        size   : 读取数据长度
*        timeout: 读取等待的最长时间(==0时，表示无限时等待)
*/
INT16U UsartRead(INT8U id, INT8U *pdest, INT32U size, INT16U timeout);

#endif
