#include "cyc_buf.h"

/********************************************************************************************************
*                                             常量、变量及宏定义
********************************************************************************************************/
// 定义μC/OS-II信号量
OS_EVENT                *SemCycBuf;               // 信号量，用于标志缓冲器中有效缓冲区的个数

// 开辟缓冲区内存
CYC_BUF_TYPE            CycBuf[CYC_BUF_MAX_CNT];

// 定义3个操作变量
CYC_BUF_TYPE *PtrIn  = (CYC_BUF_TYPE *)CycBuf;    // 写入指针，初始化在开头
CYC_BUF_TYPE *PtrOut = (CYC_BUF_TYPE *)CycBuf;    // 读出指针，初始化在开头
INT8U  CycBufCnt     = 0;                         // 有效数据个数，初始化为0

// 定义2个宏
#define CYC_BUF_BEGIN   CycBuf                    // 缓冲器第1个缓冲区的空间地址
#define CYC_BUF_END     &CycBuf[CYC_BUF_MAX_CNT]  // 缓冲器最后一个缓冲区的下一个空间地址


/********************************************************************************************************
** 函数名称： InitCycBuf
** 函数功能： 创建卫星发送数据缓冲器信号量。
** 入口参数： 无
** 出口参数： 无
********************************************************************************************************/
void InitCycBuf(void)
{
    SemCycBuf = OSSemCreate(0);                   // 创建串口接收信号量.
}

/********************************************************************************************************
** 函数名称： WrCycBuf
** 函数功能： 环形缓冲器写入操作
** 入口参数： psrc                 源数据的地址
**            len                  源数据的长度
** 出口参数： CYC_BUF_ERR_FULL     缓冲器满
**            CYC_BUF_NO_ERR       操作成功
********************************************************************************************************/
INT8U WrCycBuf(INT8U *psrc, INT32U len)
{
    OS_CPU_SR     cpu_sr;                         // Storage for CPU status register.
    
    if (CycBufCnt >= CYC_BUF_MAX_CNT)             // 缓冲器满
        return CYC_BUF_ERR_FULL;
    else
    {
    	OS_ENTER_CRITICAL();
    	
    	memcpy((INT8U *)PtrIn, psrc, len);        // 写入数据
        ++CycBufCnt;                              // 缓冲器中缓冲区个数加 1
        if (++PtrIn == CYC_BUF_END)               // 调整写入指针
        	PtrIn = CYC_BUF_BEGIN;
        
        OS_EXIT_CRITICAL();
        
        OSSemPost(SemCycBuf);
        return CYC_BUF_NO_ERR;                    // 返回写入正确
    }
}

/********************************************************************************************************
** 函数名称： RdCycBuf
** 函数功能： 环形缓冲器读出操作
** 入口参数： pdest                数据读取目的地址
** 出口参数： CYC_BUF_NO_ERR       操作成功
********************************************************************************************************/
INT8U RdCycBuf(INT8U *pdest)
{
    INT8U         err;                            // 接收μC/OS-II出错代码.
    OS_CPU_SR     cpu_sr;                         // Storage for CPU status register.
    
    OSSemPend(SemCycBuf, 0, &err);
    
    OS_ENTER_CRITICAL();    
    
    // 读出数据 
    memcpy(pdest, (INT8U *)PtrOut, (PtrOut->len[0] << 8) + PtrOut->len[1]);
    memset((INT8U *)PtrOut, 0x00, 10);

    --CycBufCnt;                                  // 缓冲区个数减 1
    if (++PtrOut == CYC_BUF_END)                  // 调整读出指针
        PtrOut = CYC_BUF_BEGIN;
    
    OS_EXIT_CRITICAL();
    
    return CYC_BUF_NO_ERR;                        // 返回读出正确
}

/********************************************************************************************************
** 函数名称： GetValidCycBufCnt
** 函数功能： 获取环形缓冲器有效缓冲区的个数
** 入口参数： 无
** 出口参数： 环形缓冲器中有效缓冲区个数
********************************************************************************************************/
INT8U GetValidCycBufCnt(void)
{
    return CycBufCnt;                             // 返回读出正确
}
