#include "bsp.h"

#ifndef CYC_BUF_H
#define CYC_BUF_H

/********************************** 数据结构定义 ******************************/
// 卫星发送数据在缓冲区中的数据结构
typedef struct cyc_buf_type{
    INT8U       name[5];                          // 指令名称
    INT8U       len[2];                           // 长度
    INT8U       user_id[3];                       // 用户地址
	              
    INT8U       msg[384];                         // 信息内容
} CYC_BUF_TYPE;


/********************************** 宏定义 ***********************************/
// 配置环形缓冲器的容量
#define CYC_BUF_MAX_CNT       10                  // 缓冲器最大容量（缓冲区个数）

// 操作返回值代码
#define CYC_BUF_NO_ERR        0                   // 操作正确
#define CYC_BUF_ERR_EMPTY     1                   // 缓冲器空
#define CYC_BUF_ERR_FULL      2                   // 缓冲器满


/********************************** 外部函数声明 ******************************/
/*
环形缓冲器初始化
*/
void InitCycBuf(void);

/*
环形缓冲器写入操作
*/
INT8U WrCycBuf(INT8U *psrc, INT32U len);

/*
环形缓冲器读出操作
*/
INT8U RdCycBuf(INT8U *pdest);

/*
获取环形缓冲器有效数据个数
*/
INT8U GetValidCycBufCnt(void);

#endif
